#!/usr/bin/env python3
"""The ledger gate: claims.toml against the theory note and the Lean kernel.

    python3 site/check_ledger.py            # the static checks only
    python3 site/check_ledger.py --lean     # also ask Lean (lean/ must be built: `lake build`)

Run by the Lean workflow after the axiom audit. Standard library only. It fails (exit 1) unless

1. every claim without `removed`, other than an experiment (`exp-*`), is math.machine-checked or
   math.disproved: the note keeps no result that is not machine-checked;
2. every such machine-checked claim names its Lean declarations (`lean`);
3. the kept claims are exactly the numbered results of doc/theory/exact-front.md: every `label` is
   the label of one numbered result, no two claims share a label, and every numbered result has a
   claim;
4. with --lean, every name in `lean` and `lean_partial` of a claim without `removed` exists in the
   Lean development and depends on no axiom beyond propext, Classical.choice and Quot.sound. The
   script writes lean/scripts/LedgerNames.lean (not committed) and runs it with `lake env lean`.

The checks read `status`, the cache of the effective status that site/gen_graph.py compares with
the history (`claimgraph status`).
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEDGER = ROOT / "claims.toml"
NOTE = ROOT / "doc" / "theory" / "exact-front.md"
LEAN = ROOT / "lean"
SCRIPT = LEAN / "scripts" / "LedgerNames.lean"
ACCEPTED = {"math.machine-checked", "math.disproved"}
RESULT = re.compile(r"^\*\*((?:Definition|Lemma|Theorem|Proposition|Corollary|Example|Conjecture)"
                    r" \d+\.\d+)\b")

LEAN_CHECK = r"""-- Generated by site/check_ledger.py from claims.toml; do not edit, do not commit.
import ZenoFront

open Lean Elab Command

/-- The declarations that the ledger's active claims name in `lean` and `lean_partial`. -/
def ledgerNames : List (String × String) := [NAMES]

#eval show CommandElabM Unit from do
  let env ← getEnv
  let allowed : List Name := [``propext, ``Classical.choice, ``Quot.sound]
  let mut bad : Array String := #[]
  for (slug, s) in ledgerNames do
    let n := s.toName
    if env.find? n |>.isNone then
      bad := bad.push s!"{slug}: no declaration {s}"
      continue
    let axs ← liftCoreM <| collectAxioms n
    let extra := axs.filter (· ∉ allowed)
    unless extra.isEmpty do
      bad := bad.push s!"{slug}: {s} depends on {extra.toList}"
  unless bad.isEmpty do
    throwError (s!"ledger gate: {bad.size} problem(s):\n" ++ String.intercalate "\n" bad.toList)
  logInfo m!"ledger gate: {ledgerNames.length} declarations exist, axioms ⊆ {allowed}"
"""


def names_of(value) -> list[str]:
    if not value:
        return []
    items = value.split(",") if isinstance(value, str) else value
    return [s.strip() for s in items if s.strip()]


def note_labels() -> list[str]:
    return [m.group(1) for line in NOTE.read_text(encoding="utf-8").splitlines()
            if (m := RESULT.match(line))]


def static_checks(claims: dict[str, dict]) -> list[str]:
    errors = []
    active = {slug: c for slug, c in claims.items() if "removed" not in c}
    for slug, c in active.items():
        if slug.startswith("exp-"):
            continue
        status = c.get("status")
        if status not in ACCEPTED:
            errors.append(f"{slug}: status {status}; a kept claim must be math.machine-checked or "
                          "math.disproved (or archived with `removed`)")
        if status == "math.machine-checked" and not names_of(c.get("lean")):
            errors.append(f"{slug}: machine-checked with no `lean`")
    labels: dict[str, str] = {}
    for slug, c in active.items():
        label = c.get("label")
        if label is None:
            continue
        if label in labels:
            errors.append(f"{slug}: label {label!r} is also {labels[label]}'s")
        labels[label] = slug
    results = note_labels()
    for label in sorted(set(labels) - set(results)):
        errors.append(f"{labels[label]}: label {label!r} is not a numbered result of {NOTE.name}")
    for label in results:
        if label not in labels:
            errors.append(f"{NOTE.name}: {label} has no claim in claims.toml (add one with this `label`)")
    if len(results) != len(set(results)):
        errors.append(f"{NOTE.name}: a label is used twice")
    return errors


def lean_check(claims: dict[str, dict]) -> int:
    pairs = sorted({(slug, name) for slug, c in claims.items() if "removed" not in c
                    for field in ("lean", "lean_partial") for name in names_of(c.get(field))})
    literal = ",\n  ".join(f"({json.dumps(slug)}, {json.dumps(name)})" for slug, name in pairs)
    SCRIPT.write_text(LEAN_CHECK.replace("[NAMES]", f"[\n  {literal}]"), encoding="utf-8")
    run = subprocess.run(["lake", "env", "lean", str(SCRIPT.relative_to(LEAN))], cwd=LEAN,
                         capture_output=True, text=True)
    sys.stdout.write(run.stdout)
    sys.stderr.write(run.stderr)
    return run.returncode


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--lean", action="store_true", help="also check the names against Lean")
    args = ap.parse_args()
    claims = tomllib.loads(LEDGER.read_text(encoding="utf-8"))["claims"]
    errors = static_checks(claims)
    for e in errors:
        print(f"ledger gate: {e}", file=sys.stderr)
    active = [s for s, c in claims.items() if "removed" not in c and not s.startswith("exp-")]
    by_status = {st: sum(1 for s in active if claims[s].get("status") == st)
                 for st in sorted({claims[s].get("status") for s in active}, key=str)}
    print(f"ledger gate: {len(active)} active claims ("
          + ", ".join(f"{n} {st}" for st, n in by_status.items()) + "), "
          f"{sum(1 for c in claims.values() if 'removed' in c)} archived, "
          f"{len(note_labels())} numbered results in the note")
    if errors:
        return 1
    if args.lean:
        return lean_check(claims)
    return 0


if __name__ == "__main__":
    sys.exit(main())
